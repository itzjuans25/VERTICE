CREATE TABLE IF NOT EXISTS sms_simulado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario VARCHAR(40) NOT NULL,
    mensaje TEXT NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS notificaciones_pendientes (
    id VARCHAR(36) PRIMARY KEY,
    contenido TEXT NOT NULL,
    intentos INTEGER DEFAULT 0 NOT NULL,
    siguiente_intento TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_notificaciones_pendientes_intentos
    ON notificaciones_pendientes (siguiente_intento, id);

CREATE TABLE IF NOT EXISTS notificacion_avisos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    asunto VARCHAR(254) NOT NULL,
    estado VARCHAR(18) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_notificacion_avisos_usuario ON notificacion_avisos (usuario_id, id DESC);
