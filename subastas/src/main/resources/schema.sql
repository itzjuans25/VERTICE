CREATE TABLE IF NOT EXISTS subasta_lotes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 semilla TEXT UNIQUE,
 titulo VARCHAR(150) NOT NULL,
 descripcion TEXT NOT NULL,
 categoria VARCHAR(24) NOT NULL,
 condicion VARCHAR(12) NOT NULL,
 atributos TEXT NOT NULL,
 imagenes TEXT NOT NULL,
 precio_inicial NUMERIC(15,2) NOT NULL CHECK (precio_inicial > 0),
 incremento NUMERIC(15,2) NOT NULL CHECK (incremento > 0),
 precio_actual NUMERIC(15,2) NOT NULL CHECK (precio_actual >= precio_inicial),
 ganador_id BIGINT,
 ganador_email VARCHAR(254),
 tienda_email VARCHAR(254) NOT NULL,
 estado VARCHAR(16) NOT NULL CHECK (estado IN ('PROGRAMADA','ACTIVA','CERRADA','ADJUDICADA','CANCELADA')),
 inicio TIMESTAMP WITH TIME ZONE NOT NULL,
 fin TIMESTAMP WITH TIME ZONE NOT NULL CHECK (fin > inicio),
 pujas INTEGER NOT NULL DEFAULT 0,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_subasta_estado_fin ON subasta_lotes(estado,fin);
CREATE INDEX IF NOT EXISTS ix_subasta_categoria_condicion ON subasta_lotes(categoria,condicion);
CREATE TABLE IF NOT EXISTS subasta_pujas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lote_id BIGINT NOT NULL REFERENCES subasta_lotes(id),
 usuario_id BIGINT NOT NULL,
 monto NUMERIC(15,2) NOT NULL,
 fecha TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_subasta_pujas_lote ON subasta_pujas(lote_id,id);
CREATE INDEX IF NOT EXISTS ix_subasta_pujas_usuario ON subasta_pujas(usuario_id,id);
CREATE TABLE IF NOT EXISTS subasta_ordenes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lote_id BIGINT NOT NULL UNIQUE REFERENCES subasta_lotes(id),
 usuario_id BIGINT NOT NULL,
 monto NUMERIC(15,2) NOT NULL,
 pagada TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_subasta_orden_usuario ON subasta_ordenes(usuario_id,id);
CREATE TABLE IF NOT EXISTS subasta_avisos (
 clave VARCHAR(100) PRIMARY KEY,
 destino VARCHAR(254) NOT NULL,
 asunto VARCHAR(120) NOT NULL,
 mensaje TEXT NOT NULL,
 intentos INTEGER NOT NULL DEFAULT 0,
 reintentar TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 enviado TIMESTAMP WITH TIME ZONE
);
ALTER TABLE subasta_avisos ADD COLUMN IF NOT EXISTS usuario_id BIGINT;
